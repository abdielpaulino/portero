import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFileSync } from "node:fs";
import { it } from "node:test";
import { Client, Pool } from "pg";
import { hash, presentSale, validateSale } from "../src/sales/domain.js";
import { createSalesRepository } from "../src/sales/repository.js";
import { inputBody, key } from "./sales-fixture.js";
import { createInvitationRepository } from "../src/auth/invitations.js";
import { createConferenceRepository, validateConference } from "../src/operations/conferences.js";
import { createSettingsRepository, defaultSettings } from "../src/operations/settings.js";

const localUrl = process.env.PORTERO_LOCAL_PG_URL;
const quote = (name: string) => `"${name.replaceAll('"', '""')}"`;
const migration = readFileSync(new URL("../sql/20261122-external-sales.sql", import.meta.url), "utf8");
const review = readFileSync(new URL("../sql/20261122-external-sales-review.sql", import.meta.url), "utf8");
const operational = readFileSync(new URL("../sql/20261122-operational-extension.sql", import.meta.url), "utf8");
const operationalReview = readFileSync(new URL("../sql/20261122-operational-review.sql", import.meta.url), "utf8");

// Nunca usa DATABASE_URL ou .env. Cria e remove somente um banco novo em servidor local explícito.
it("migração e repositórios no PostgreSQL local descartável", { skip: localUrl ? false : "PORTERO_LOCAL_PG_URL não informado; PostgreSQL real não validado", timeout: 60_000 }, async t => {
  const target = new URL(localUrl!);
  assert.ok(["postgres:", "postgresql:"].includes(target.protocol));
  assert.ok(["127.0.0.1", "[::1]"].includes(target.hostname), "Somente endereço de loopback literal");
  assert.equal(target.pathname, "/portero_local_tests", "Exige banco administrativo local exclusivo para testes");
  assert.equal(target.search, "", "Parâmetros adicionais de conexão não são permitidos");
  const admin = new Client({ connectionString: target.href, connectionTimeoutMillis: 2_000 });
  const name = `portero_sales_review_${randomUUID().replaceAll("-", "")}`;
  const role = `${name}_api`, createdRoles: string[] = [];
  let created = false;
  const pools: Pool[] = [];
  await admin.connect();
  try {
    const address = await admin.query("SELECT inet_server_addr()::text AS address");
    assert.ok(["127.0.0.1", "::1"].includes(address.rows[0].address), "O servidor também precisa ser local");
    for (const candidate of ["anon", "authenticated", role]) {
      const exists = await admin.query("SELECT 1 FROM pg_roles WHERE rolname=$1", [candidate]);
      if (!exists.rowCount) { await admin.query(`CREATE ROLE ${quote(candidate)} NOLOGIN NOBYPASSRLS`); createdRoles.push(candidate); }
    }
    await admin.query(`CREATE DATABASE ${quote(name)}`); created = true;
    target.pathname = `/${name}`;
    const database = new Pool({ connectionString: target.href, max: 3, connectionTimeoutMillis: 2_000 });
    const control = new Pool({ connectionString: target.href, max: 3, connectionTimeoutMillis: 2_000 });
    pools.push(database, control);

    // Fixture obtida dos metadados confirmados, sem usar os SQLs abandonados ou registros da demo.
    const original = JSON.parse(readFileSync(new URL("../sql/original-schema-confirmed.json", import.meta.url), "utf8"));
    for (const table of original.tabelas) {
      const columns = table.colunas.map((column: { nome: string; definicao: { tipo: string; identidade: string; not_null: boolean; default_ou_expressao: string | null } }) => {
        const d = column.definicao;
        return `${quote(column.nome)} ${d.tipo}${d.identidade === "d" ? " GENERATED BY DEFAULT AS IDENTITY" : ""}${d.not_null ? " NOT NULL" : ""}${d.default_ou_expressao ? ` DEFAULT ${d.default_ou_expressao}` : ""}`;
      });
      await database.query(`CREATE TABLE ${table.nome} (${columns.join(",")})`);
    }
    for (const table of original.tabelas) {
      for (const constraint of [...table.constraints].sort((a, b) => Number(a.definicao.tipo === "f") - Number(b.definicao.tipo === "f"))) {
        await database.query(`ALTER TABLE ${table.nome} ADD CONSTRAINT ${quote(constraint.nome)} ${constraint.definicao.definicao}`);
      }
      if (table.propriedades.rls) await database.query(`ALTER TABLE ${table.nome} ENABLE ROW LEVEL SECURITY`);
    }
    const snapshot = async () => (await database.query(`SELECT c.relname,c.relrowsecurity,a.attname,format_type(a.atttypid,a.atttypmod) AS type,
      a.attnotnull,a.attidentity,pg_get_expr(d.adbin,d.adrelid) AS default_value,
      (SELECT jsonb_agg(pg_get_constraintdef(k.oid) ORDER BY k.conname) FROM pg_constraint k WHERE k.conrelid=c.oid) AS constraints,
      (SELECT jsonb_agg(i.indexdef ORDER BY i.indexname) FROM pg_indexes i WHERE i.schemaname='public' AND i.tablename=c.relname) AS indexes
      FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace JOIN pg_attribute a ON a.attrelid=c.oid
      LEFT JOIN pg_attrdef d ON d.adrelid=c.oid AND d.adnum=a.attnum WHERE n.nspname='public'
      AND c.relname IN ('lojas','usuarios_app','acessos_permitidos','baixas_estoque') AND a.attnum>0 AND NOT a.attisdropped ORDER BY c.relname,a.attnum`)).rows;
    const before = await snapshot();
    await database.query(review);
    await database.query(operational);
    await database.query(operationalReview);
    assert.deepEqual(await snapshot(), before);
    const ddl = await database.connect();
    try {
      await ddl.query(migration);
      await assert.rejects(ddl.query(migration), { code: "42P07" });
      await ddl.query("ROLLBACK");
    } finally { ddl.release(); }
    assert.deepEqual(await snapshot(), before, "A migração não altera definições originais");
    await database.query(review);
    await database.query(`INSERT INTO lojas(id,nuvemshop_store_id,access_token,nome_loja,status) VALUES (10,'123','ficticio','Teste','ativa'),(20,'999','ficticio','Outra','ativa');
      INSERT INTO usuarios_app(id,loja_id,nome,email,senha_hash) VALUES (1,10,'A','a@example.test','ficticio'),(2,10,'B','b@example.test','ficticio'),(11,20,'C','c@example.test','ficticio')`);
    await database.query("SELECT setval(pg_get_serial_sequence('public.usuarios_app','id'),(SELECT max(id) FROM usuarios_app))");
    const auth = { usuarioId: 1, lojaId: 10 }, repository = createSalesRepository(database, control, "123");
    const input = validateSale(inputBody), prepared = input.itens.map(item => ({ ...item, nomeProduto: "Luva", nomeVariante: item.varianteId, sku: null }));
    let saleId = 0, baixaId = 0;
    await t.test("criação concorrente única, totais calculados e rollback de item inválido", async () => {
      const sales = await Promise.all([repository.create(auth, key, hash(input), input, prepared), repository.create(auth, key, hash(input), input, prepared)]);
      assert.equal(sales[0].id, sales[1].id); saleId = sales[0].id;
      assert.equal(presentSale(sales[0]).total, "50.00");
      assert.equal(presentSale(sales[0]).valorEstornado, "0.00");
      assert.equal((await database.query("SELECT count(*) FROM itens_venda_externa")).rows[0].count, "2");
      assert.equal((await database.query("SELECT count(*) FROM baixas_estoque")).rows[0].count, "0");
      await assert.rejects(repository.create(auth, randomUUID(), hash(input), input, [{ ...prepared[0], quantidade: 0 }]));
      assert.equal((await database.query("SELECT count(*) FROM vendas_externas")).rows[0].count, "1");
      assert.equal((await database.query("SELECT count(*) FROM movimentos_financeiros_venda")).rows[0].count, "1");
      const summary = await repository.summary(auth, "2026-11");
      assert.deepEqual(summary.diario, [{ dia: "2026-11-01", moeda: "BRL", valor: "50.00" }]);
      assert.deepEqual(summary.gestao?.porMoeda, [{ moeda: "BRL", valorAReceber: "45.00", unidades: String(input.itens.reduce((sum, row) => sum + row.quantidade, 0)) }]);
      assert.equal(summary.gestao?.vendasComPendencia, 1);
      assert.equal(summary.gestao?.produtosMaisVendidos.length, new Set(input.itens.map(row => row.produtoId)).size);
    });
    await t.test("PostgreSQL rejeita NaN, infinitos, negativos, overflow e fração excedente", async () => {
      const columns = { vendas_externas: ["subtotal", "descontos_itens", "desconto_venda", "total", "valor_recebido", "valor_estornado"],
        itens_venda_externa: ["preco_unitario", "desconto", "total"], movimentos_financeiros_venda: ["valor"] };
      for (const [table, fields] of Object.entries(columns)) for (const column of fields) {
        for (const value of ["NaN", "Infinity", "-Infinity", "-0.01", "10000000000000000.00", "0.001"]) {
          await assert.rejects(database.query(`UPDATE ${quote(table)} SET ${quote(column)}=$1`, [value]), { code: "23514" });
        }
        await assert.rejects(database.query(`UPDATE ${quote(table)} SET ${quote(column)}=$1`, ["texto"]), { code: "22P02" });
      }
      await assert.rejects(database.query("UPDATE vendas_externas SET subtotal='NaN',descontos_itens='NaN',desconto_venda='NaN',total='NaN',valor_recebido='NaN',valor_estornado='NaN'"), { code: "23514" });
      await assert.rejects(database.query("UPDATE itens_venda_externa SET preco_unitario='NaN',desconto='NaN',total='NaN'"), { code: "23514" });
    });
    await t.test("financeiro atômico, concorrência, repetição, estorno e cancelamento", async () => {
      const eventKey = randomUUID(), event = { tipo: "recebimento" as const, valor: "45.00", formaPagamento: "Pix", ocorridoEm: "2026-11-10T12:00:00.000Z" };
      const simultaneous = await Promise.allSettled([repository.financial(auth, saleId, eventKey, event), repository.financial(auth, saleId, eventKey, event)]);
      assert.ok(simultaneous.some(result => result.status === "fulfilled"));
      for (const result of simultaneous) if (result.status === "rejected") assert.equal(result.reason.status, 409);
      await repository.financial(auth, saleId, eventKey, event);
      assert.equal((await repository.get(auth, saleId)).movimentos.length, 2);
      await assert.rejects(repository.financial(auth, saleId, eventKey, { ...event, valor: "44.00" }), { status: 409 });
      await repository.financial(auth, saleId, randomUUID(), { ...event, tipo: "estorno", valor: "10.00" });
      // Falha depois do INSERT real: o ROLLBACK precisa remover o movimento.
      const failing = { async connect() {
        const client = await database.connect();
        return new Proxy(client, { get(target, property) {
          if (property === "query") return (text: string, values?: unknown[]) => {
            if (text.startsWith("UPDATE vendas_externas")) throw new Error("Falha simulada após INSERT");
            return client.query(text, values);
          };
          const value = Reflect.get(target, property); return typeof value === "function" ? value.bind(target) : value;
        } });
      } } as unknown as Pool;
      const broken = createSalesRepository(failing, control, "123"), failureKey = randomUUID();
      await assert.rejects(broken.financial(auth, saleId, failureKey, { ...event, valor: "10.00" }));
      assert.equal((await database.query("SELECT count(*) FROM movimentos_financeiros_venda WHERE requisicao_id=$1", [failureKey])).rows[0].count, "0");
      assert.equal((await repository.get(auth, saleId)).valorRecebido, "50.00");
      await repository.financial(auth, saleId, failureKey, { ...event, valor: "10.00" });
      assert.equal((await repository.get(auth, saleId)).valorRecebido, "60.00");
      await assert.rejects(repository.financial(auth, saleId, randomUUID(), { ...event, valor: "0.01" }), { status: 400 });
    });
    await t.test("isolamento de loja e correspondência entre item e baixa antes da execução", async () => {
      await assert.rejects(repository.get({ usuarioId: 1, lojaId: 20 }, saleId), { status: 403 });
      await assert.rejects(repository.cancel({ usuarioId: 2, lojaId: 10 }, saleId), { status: 403 });
      const sale = await repository.get(auth, saleId);
      baixaId = await repository.withSale(auth, saleId, () => repository.prepareItem(auth, saleId, sale.itens[0].id));
      const previous = process.env.DATABASE_URL;
      process.env.DATABASE_URL = "postgresql://offline:offline@127.0.0.1:1/offline";
      let factory: typeof import("../src/stock/repository.js").createStockRepository;
      try { factory = (await import("../src/stock/repository.js")).createStockRepository; }
      finally { if (previous === undefined) delete process.env.DATABASE_URL; else process.env.DATABASE_URL = previous; }
      const stock = factory(database, false);
      for (const [column, value, original] of [["produto_id", "999", "100"], ["variant_id", "999", "101"], ["quantidade_baixada", 3, 1], ["usuario_id", 2, 1], ["loja_id", 20, 10]] as const) {
        await database.query(`UPDATE baixas_estoque SET ${quote(column)}=$1 WHERE id=$2`, [value, baixaId]);
        await assert.rejects(stock.withLock(auth, baixaId, async () => assert.fail("Vínculo inválido não pode executar")));
        await database.query(`UPDATE baixas_estoque SET ${quote(column)}=$1 WHERE id=$2`, [original, baixaId]);
      }
      await repository.cancel(auth, saleId);
      const summary = await repository.summary(auth, "2026-11");
      assert.deepEqual(summary.diario, []); assert.deepEqual(summary.gestao?.porMoeda, []); assert.deepEqual(summary.gestao?.produtosMaisVendidos, []);
      assert.equal(summary.gestao?.vendasComPendencia, 0);
      const event = { tipo: "recebimento" as const, valor: "1.00", formaPagamento: "Pix", ocorridoEm: "2026-11-10T12:00:00.000Z" };
      await assert.rejects(repository.financial(auth, saleId, randomUUID(), event), { status: 400 });
      await repository.financial(auth, saleId, randomUUID(), { ...event, tipo: "estorno", valor: "50.00" });
      const final = presentSale(await repository.get(auth, saleId));
      assert.equal(final.situacaoPagamento, "estornado"); assert.equal(final.movimentos.length, 5);
      assert.equal((await database.query("SELECT status_sincronizacao FROM baixas_estoque WHERE id=$1", [baixaId])).rows[0].status_sincronizacao, "registrada");
    });
    await t.test("permissões e RLS não concedem acesso ao navegador; backend restrito exige policy", async () => {
      const client = await database.connect();
      try {
        for (const actor of ["anon", "authenticated"]) {
          await client.query(`SET ROLE ${quote(actor)}`);
          await assert.rejects(client.query("SELECT * FROM vendas_externas"), { code: "42501" });
          await assert.rejects(client.query("SELECT nextval('vendas_externas_id_seq')"), { code: "42501" });
          await client.query("RESET ROLE");
        }
        await client.query(`GRANT USAGE ON SCHEMA public TO ${quote(role)}; GRANT SELECT ON vendas_externas TO ${quote(role)}`);
        await client.query(`SET ROLE ${quote(role)}`);
        assert.equal((await client.query("SELECT * FROM vendas_externas")).rowCount, 0, "GRANT isolado não contorna RLS");
        await client.query("RESET ROLE");
        await client.query(`CREATE POLICY backend_review_read ON vendas_externas FOR SELECT TO ${quote(role)} USING (true)`);
        await client.query(`SET ROLE ${quote(role)}`);
        assert.equal((await client.query("SELECT * FROM vendas_externas")).rowCount, 1);
      } finally { await client.query("RESET ROLE"); client.release(); }
    });
    await t.test("convite real é consumido uma vez, não substitui contas e rejeita expiração", async () => {
      await database.query("DELETE FROM usuarios_app WHERE loja_id=20; DELETE FROM lojas WHERE id=20");
      const invitations = createInvitationRepository(database, "123"), invite = await invitations.issue("felipe@example.test");
      const attempts = await Promise.allSettled([invitations.activate(invite.secret, "Felipe", "senha-local-apenas-teste", "senha-local-apenas-teste"), invitations.activate(invite.secret, "Felipe", "senha-local-apenas-teste", "senha-local-apenas-teste")]);
      assert.equal(attempts.filter(result => result.status === "fulfilled").length, 1);
      assert.equal((await database.query("SELECT count(*) FROM usuarios_app WHERE email='felipe@example.test'")).rows[0].count, "1");
      await assert.rejects(invitations.inspect(invite.secret), { status: 410 });
      const expired = await invitations.issue("expirado@example.test");
      await database.query("UPDATE convites_conta SET criado_em=now()-interval '2 days',expira_em=now()-interval '1 day' WHERE email='expirado@example.test'");
      await assert.rejects(invitations.inspect(expired.secret), { status: 410 });
    });
    await t.test("conferência auditada não envia estoque e mantém vínculo, idempotência e exclusão", async () => {
      await database.query("UPDATE baixas_estoque SET status_sincronizacao='incerta' WHERE id=$1", [baixaId]);
      const conferences = createConferenceRepository(database, "123"), request = randomUUID();
      const body = validateConference({ conclusao: "inconclusiva", quantidadeComprovada: null, evidenciaTipo: "registro_movimentacao", evidenciaReferencia: "MOVIMENTO-LOCAL-TESTE", justificativa: "Evidência ainda insuficiente para comprovar o desconto.", confirmoEvidencia: true });
      const result = await conferences.resolve(auth, baixaId, request, body);
      assert.equal((await conferences.resolve(auth, baixaId, request, body)).id, result.id);
      assert.equal((await database.query("SELECT status_sincronizacao FROM baixas_estoque WHERE id=$1", [baixaId])).rows[0].status_sincronizacao, "incerta");
      await conferences.resolve(auth, baixaId, randomUUID(), validateConference({ ...body, conclusao: "integral", quantidadeComprovada: 1 }));
      assert.equal((await conferences.list(auth, baixaId)).items.length, 2);
    });
    await t.test("preferências e deduplicação de alertas sobrevivem à nova instância", async () => {
      const settings = createSettingsRepository(database, control, "123");
      await settings.save(auth, { ...defaultSettings, notificacoesAtivas: true, emailNotificacoes: "felipe@example.test" });
      await assert.rejects(settings.save(auth, defaultSettings), { status: 409 });
      let sent = 0;
      const products = { async list() { return { page: 1, nextPage: null, items: [{ id: "100:101", produtoId: "100", varianteId: "101", nome: "Luva", variante: "Azul", sku: null, preco: 10, quantidade: -1, ruptura: true }] }; } } as unknown as Parameters<typeof settings.monitor>[0];
      const sender = async () => { sent++; return "provedor-ficticio"; };
      await settings.monitor(products, sender);
      await createSettingsRepository(database, control, "123").monitor(products, sender);
      assert.equal(sent, 1); assert.equal((await database.query("SELECT estado FROM alertas_estoque")).rows[0].estado, "enviado");
    });
    await t.test("exclusão respeita FKs novas e originais sem deixar itens ou movimentos", async () => {
      await assert.rejects(database.query("DELETE FROM baixas_estoque WHERE id=$1", [baixaId]), { code: "23503" });
      await assert.rejects(database.query("DELETE FROM usuarios_app WHERE id=1"), { code: "23503" });
      await database.query("DELETE FROM usuarios_app WHERE loja_id=20; DELETE FROM lojas WHERE id=20");
      const { createWebhookRepository } = await import("../src/nuvemshop/webhook-repository.js");
      await createWebhookRepository(database, 5_000).handle("123", "app/store_redact");
      for (const table of ["convites_conta", "conferencias_baixa", "alertas_estoque", "configuracoes_loja", "movimentos_financeiros_venda", "itens_venda_externa", "vendas_externas", "baixas_estoque", "usuarios_app", "acessos_permitidos", "lojas"]) {
        assert.equal((await database.query(`SELECT count(*) FROM ${quote(table)}`)).rows[0].count, "0");
      }
      assert.deepEqual(await snapshot(), before);
    });
  } finally {
    await Promise.all(pools.map(pool => pool.end()));
    try {
      if (created) await admin.query(`DROP DATABASE ${quote(name)}`);
      for (const candidate of createdRoles.reverse()) await admin.query(`DROP ROLE ${quote(candidate)}`);
    } finally { await admin.end(); }
  }
});
