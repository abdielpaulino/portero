BEGIN;

CREATE TABLE public.vendas_externas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loja_id integer NOT NULL CONSTRAINT vendas_externas_loja_id_lojas_id_fk REFERENCES public.lojas(id),
  usuario_id integer NOT NULL CONSTRAINT vendas_externas_usuario_id_usuarios_app_id_fk REFERENCES public.usuarios_app(id),
  requisicao_id uuid NOT NULL,
  conteudo_hash text NOT NULL CHECK (conteudo_hash ~ '^[a-f0-9]{64}$'),
  canal text NOT NULL CHECK (length(btrim(canal)) BETWEEN 1 AND 80),
  forma_pagamento text NOT NULL CHECK (length(btrim(forma_pagamento)) BETWEEN 1 AND 80),
  moeda text NOT NULL CHECK (moeda ~ '^[A-Z]{3}$'),
  vendida_em timestamptz NOT NULL DEFAULT now(),
  situacao text NOT NULL DEFAULT 'confirmada' CHECK (situacao IN ('confirmada', 'cancelada')),
  -- Sem typmod: rejeitar frações excedentes, em vez de arredondá-las antes do CHECK.
  subtotal numeric NOT NULL CHECK (subtotal <> 'NaN'::numeric AND subtotal BETWEEN 0 AND 9999999999999999.99 AND scale(subtotal) <= 2),
  descontos_itens numeric NOT NULL CHECK (descontos_itens <> 'NaN'::numeric AND descontos_itens BETWEEN 0 AND 9999999999999999.99 AND scale(descontos_itens) <= 2),
  desconto_venda numeric NOT NULL CHECK (desconto_venda <> 'NaN'::numeric AND desconto_venda BETWEEN 0 AND 9999999999999999.99 AND scale(desconto_venda) <= 2),
  total numeric NOT NULL CHECK (total <> 'NaN'::numeric AND total BETWEEN 0 AND 9999999999999999.99 AND scale(total) <= 2 AND total = subtotal - descontos_itens - desconto_venda),
  valor_recebido numeric NOT NULL DEFAULT 0 CHECK (valor_recebido <> 'NaN'::numeric AND valor_recebido BETWEEN 0 AND 9999999999999999.99 AND scale(valor_recebido) <= 2),
  valor_estornado numeric NOT NULL DEFAULT 0 CHECK (valor_estornado <> 'NaN'::numeric AND valor_estornado BETWEEN 0 AND 9999999999999999.99 AND scale(valor_estornado) <= 2),
  criada_em timestamptz NOT NULL DEFAULT now(),
  cancelada_em timestamptz,
  CONSTRAINT vendas_externas_requisicao_unique UNIQUE (loja_id, requisicao_id),
  CONSTRAINT vendas_externas_financeiro_check CHECK (valor_recebido >= 0 AND valor_recebido - valor_estornado <= total AND valor_estornado >= 0 AND valor_estornado <= valor_recebido),
  CONSTRAINT vendas_externas_cancelamento_check CHECK ((situacao = 'cancelada') = (cancelada_em IS NOT NULL))
);

CREATE TABLE public.itens_venda_externa (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venda_id integer NOT NULL CONSTRAINT itens_venda_externa_venda_id_vendas_externas_id_fk REFERENCES public.vendas_externas(id) ON DELETE CASCADE,
  produto_id text NOT NULL CHECK (produto_id ~ '^[1-9][0-9]{0,19}$'),
  variante_id text NOT NULL CHECK (variante_id ~ '^[1-9][0-9]{0,19}$'),
  nome_produto text NOT NULL,
  nome_variante text NOT NULL,
  sku text,
  quantidade integer NOT NULL CHECK (quantidade > 0),
  preco_unitario numeric NOT NULL CHECK (preco_unitario <> 'NaN'::numeric AND preco_unitario BETWEEN 0 AND 9999999999999999.99 AND scale(preco_unitario) <= 2),
  desconto numeric NOT NULL CHECK (desconto <> 'NaN'::numeric AND desconto BETWEEN 0 AND 9999999999999999.99 AND scale(desconto) <= 2),
  total numeric NOT NULL CHECK (total <> 'NaN'::numeric AND total BETWEEN 0 AND 9999999999999999.99 AND scale(total) <= 2 AND total = quantidade::numeric * preco_unitario - desconto),
  baixa_id integer CONSTRAINT itens_venda_externa_baixa_id_unique UNIQUE CONSTRAINT itens_venda_externa_baixa_id_baixas_estoque_id_fk REFERENCES public.baixas_estoque(id),
  CONSTRAINT itens_venda_externa_variante_unique UNIQUE (venda_id, variante_id)
);

CREATE TABLE public.movimentos_financeiros_venda (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venda_id integer NOT NULL CONSTRAINT movimentos_financeiros_venda_venda_id_vendas_externas_id_fk REFERENCES public.vendas_externas(id) ON DELETE CASCADE,
  usuario_id integer NOT NULL CONSTRAINT movimentos_financeiros_venda_usuario_id_usuarios_app_id_fk REFERENCES public.usuarios_app(id),
  requisicao_id uuid NOT NULL,
  conteudo_hash text NOT NULL CHECK (conteudo_hash ~ '^[a-f0-9]{64}$'),
  tipo text NOT NULL CHECK (tipo IN ('recebimento', 'estorno')),
  valor numeric NOT NULL CHECK (valor <> 'NaN'::numeric AND valor BETWEEN 0 AND 9999999999999999.99 AND scale(valor) <= 2 AND valor > 0),
  forma_pagamento text NOT NULL CHECK (length(btrim(forma_pagamento)) BETWEEN 1 AND 80),
  ocorrido_em timestamptz NOT NULL,
  registrado_em timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT movimentos_financeiros_venda_requisicao_unique UNIQUE (venda_id, requisicao_id)
);

CREATE INDEX vendas_externas_loja_data_idx ON public.vendas_externas (loja_id, vendida_em DESC, id DESC);
CREATE INDEX movimentos_financeiros_venda_data_idx ON public.movimentos_financeiros_venda (ocorrido_em, venda_id);
ALTER TABLE public.vendas_externas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.itens_venda_externa ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.movimentos_financeiros_venda ENABLE ROW LEVEL SECURITY;

-- O papel SQL da API precisa ser conferido separadamente; não conceder acesso ao navegador.
REVOKE ALL ON public.vendas_externas, public.itens_venda_externa, public.movimentos_financeiros_venda FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.vendas_externas_id_seq, public.itens_venda_externa_id_seq, public.movimentos_financeiros_venda_id_seq FROM PUBLIC, anon, authenticated;

COMMIT;
