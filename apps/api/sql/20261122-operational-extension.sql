BEGIN;

CREATE TABLE public.convites_conta (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loja_id integer NOT NULL REFERENCES public.lojas(id) ON DELETE CASCADE,
  email text NOT NULL CHECK (email = lower(btrim(email)) AND length(email) BETWEEN 3 AND 254),
  segredo_hash text NOT NULL UNIQUE CHECK (segredo_hash ~ '^[a-f0-9]{64}$'),
  expira_em timestamptz NOT NULL,
  criado_em timestamptz NOT NULL DEFAULT now(),
  usado_em timestamptz,
  revogado_em timestamptz,
  usuario_id integer REFERENCES public.usuarios_app(id) ON DELETE SET NULL,
  CONSTRAINT convites_conta_expiracao_check CHECK (expira_em > criado_em),
  CONSTRAINT convites_conta_consumo_check CHECK (usado_em IS NULL OR revogado_em IS NULL)
);
CREATE UNIQUE INDEX convites_conta_ativo_email_idx ON public.convites_conta(loja_id,email)
  WHERE usado_em IS NULL AND revogado_em IS NULL;

CREATE TABLE public.conferencias_baixa (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loja_id integer NOT NULL REFERENCES public.lojas(id),
  baixa_id integer NOT NULL REFERENCES public.baixas_estoque(id),
  usuario_id integer NOT NULL REFERENCES public.usuarios_app(id),
  requisicao_id uuid NOT NULL,
  conteudo_hash text NOT NULL CHECK (conteudo_hash ~ '^[a-f0-9]{64}$'),
  conclusao text NOT NULL CHECK (conclusao IN ('integral','nao_aplicada','parcial','inconclusiva')),
  quantidade_comprovada integer CHECK (quantidade_comprovada >= 0),
  evidencia_tipo text NOT NULL CHECK (evidencia_tipo IN ('registro_movimentacao','documento_operacional')),
  evidencia_referencia text NOT NULL CHECK (length(btrim(evidencia_referencia)) BETWEEN 8 AND 500),
  justificativa text NOT NULL CHECK (length(btrim(justificativa)) BETWEEN 20 AND 2000),
  status_anterior text NOT NULL,
  status_final text NOT NULL,
  criado_em timestamptz NOT NULL DEFAULT now(),
  UNIQUE (loja_id,requisicao_id),
  CONSTRAINT conferencias_baixa_conclusao_quantidade_check CHECK ((conclusao='inconclusiva') = (quantidade_comprovada IS NULL))
);
CREATE INDEX conferencias_baixa_operacao_idx ON public.conferencias_baixa(baixa_id,id DESC);

CREATE TABLE public.configuracoes_loja (
  loja_id integer PRIMARY KEY REFERENCES public.lojas(id) ON DELETE CASCADE,
  limite_ruptura integer NOT NULL DEFAULT 0 CHECK (limite_ruptura BETWEEN 0 AND 2147483647),
  notificacoes_ativas boolean NOT NULL DEFAULT false,
  email_notificacoes text CHECK (length(email_notificacoes) BETWEEN 3 AND 254 AND email_notificacoes=lower(btrim(email_notificacoes))),
  atualizacao_automatica boolean NOT NULL DEFAULT true,
  intervalo_segundos integer NOT NULL DEFAULT 60 CHECK (intervalo_segundos BETWEEN 60 AND 3600),
  versao integer NOT NULL DEFAULT 1 CHECK (versao>0),
  atualizado_por integer NOT NULL REFERENCES public.usuarios_app(id),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  monitor_proxima_pagina integer NOT NULL DEFAULT 1 CHECK (monitor_proxima_pagina BETWEEN 1 AND 10000),
  monitor_id uuid,
  monitor_em timestamptz,
  monitor_resultado text,
  CONSTRAINT configuracoes_loja_destinatario_check CHECK (NOT notificacoes_ativas OR email_notificacoes IS NOT NULL)
);

CREATE TABLE public.alertas_estoque (
  loja_id integer NOT NULL REFERENCES public.configuracoes_loja(loja_id) ON DELETE CASCADE,
  variante_id text NOT NULL CHECK (variante_id ~ '^[1-9][0-9]{0,19}$'),
  produto_id text NOT NULL CHECK (produto_id ~ '^[1-9][0-9]{0,19}$'),
  nome_produto text NOT NULL,
  quantidade integer,
  limite integer NOT NULL CHECK (limite>=0),
  abaixo_limite boolean NOT NULL,
  evento_id uuid NOT NULL UNIQUE,
  estado text NOT NULL CHECK (estado IN ('normal','pendente','em_envio','enviado','incerto','falhou')),
  destinatario text,
  observado_em timestamptz NOT NULL DEFAULT now(),
  envio_iniciado_em timestamptz,
  enviado_em timestamptz,
  provedor_id text,
  PRIMARY KEY(loja_id,variante_id),
  CONSTRAINT alertas_estoque_saldo_check CHECK (NOT abaixo_limite OR quantidade IS NOT NULL),
  CONSTRAINT alertas_estoque_destinatario_check CHECK (estado NOT IN ('pendente','em_envio','enviado') OR destinatario IS NOT NULL)
);

ALTER TABLE public.convites_conta ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.conferencias_baixa ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.configuracoes_loja ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.alertas_estoque ENABLE ROW LEVEL SECURITY;
